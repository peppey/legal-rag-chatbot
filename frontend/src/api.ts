
import type { ChatMessage, DocumentItem, Source } from "./types";

const DEMO_MODE = import.meta.env.VITE_DEMO_MODE !== "false";

type ChatResponse = {
  answer: string;
  sources: Source[];
};

function createId(): string {
  return crypto.randomUUID();
}

async function request<T>(
  path: string,
  init?: RequestInit
): Promise<T> {
  const response = await fetch(path, init);

  if (!response.ok) {
    const detail = await response.text();
    throw new Error(
      `API-Fehler (${response.status}): ${detail || response.statusText}`
    );
  }

  return response.json() as Promise<T>;
}

export async function uploadDocument(file: File): Promise<DocumentItem> {
  const id = createId();

  if (DEMO_MODE) {
    return {
      id,
      name: file.name,
      type: file.type || "application/octet-stream",
      size: file.size,
      uploadedAt: new Date().toISOString(),
      fileUrl: URL.createObjectURL(file),
      file
    };
  }

  const formData = new FormData();
  formData.append("file", file);

  const result = await request<{
    id: string;
    name: string;
    type?: string;
    size?: number;
    uploaded_at?: string;
  }>("/api/documents/upload", {
    method: "POST",
    body: formData
  });

  return {
    id: result.id,
    name: result.name,
    type: result.type || file.type,
    size: result.size ?? file.size,
    uploadedAt: result.uploaded_at || new Date().toISOString(),
    fileUrl: `/api/documents/${result.id}/file`
  };
}

export async function askQuestion(
  question: string,
  documents: DocumentItem[],
  history: ChatMessage[]
): Promise<ChatResponse> {
  if (DEMO_MODE) {
    const firstDocument = documents[0];

    // Demonstration only: this answer is not generated by an LLM
    // and does not represent a real retrieval result.
    return {
      answer: firstDocument
        ? `Das ist eine Beispielantwort im Demo-Modus. Deine Frage war: „${question}“.\n\nSobald das Backend angeschlossen ist, wird hier die tatsächliche Antwort deines RAG-Systems erscheinen. Aktuell wurde der Dokumentinhalt nicht analysiert.`
        : "Lade zuerst ein Dokument hoch. Im Demo-Modus wird noch keine echte Dokumentensuche ausgeführt.",
      sources: firstDocument
        ? [
            {
              documentId: firstDocument.id,
              documentName: firstDocument.name,
              page: 1,
              excerpt: "Beispielquelle – kein tatsächlich abgerufener Text."
            }
          ]
        : []
    };
  }

  return request<ChatResponse>("/api/chat", {
    method: "POST",
    headers: {
      "Content-Type": "application/json"
    },
    body: JSON.stringify({
      question,
      document_ids: documents.map((document) => document.id),
      history: history.map(({ role, content }) => ({ role, content }))
    })
  });
}

export function isDemoMode(): boolean {
  return DEMO_MODE;
}
