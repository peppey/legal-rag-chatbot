
import { authFetch, authHeaders } from "./auth";
import type { ChatMessage, DocumentItem, Source } from "./types";

const DEMO_MODE = import.meta.env.VITE_DEMO_MODE !== "false";

type ChatResponse = {
  answer: string;
  sources: Source[];
};

function createId(): string {
  return crypto.randomUUID();
}

async function request<T>(
  path: string,
  init?: RequestInit
): Promise<T> {
  const response = await authFetch(path, init);

  if (!response.ok) {
    throw new Error(await errorMessage(response));
  }

  return response.json() as Promise<T>;
}

async function errorMessage(response: Response): Promise<string> {
  const body = await response.text();
  try {
    const { detail } = JSON.parse(body);
    if (typeof detail === "string") return detail;
  } catch {
    // not JSON, fall through to the raw text
  }
  return `API-Fehler (${response.status}): ${body || response.statusText}`;
}

export async function deleteDocument(id: string): Promise<void> {
  if (DEMO_MODE) return;
  await authFetch(`/api/documents/${id}`, { method: "DELETE" });
}

export type PdfSource = string | { url: string; httpHeaders: Record<string, string> };

// Documents from the backend need the token; the PDF viewer sends it as a header.
export async function pdfSource(fileUrl: string): Promise<PdfSource> {
  if (DEMO_MODE || !fileUrl.startsWith("/api/")) return fileUrl;
  return { url: fileUrl, httpHeaders: await authHeaders() };
}

export async function openFile(fileUrl: string): Promise<void> {
  if (DEMO_MODE || !fileUrl.startsWith("/api/")) {
    window.open(fileUrl, "_blank", "noreferrer");
    return;
  }
  const response = await authFetch(fileUrl);
  if (!response.ok) throw new Error(await errorMessage(response));
  window.open(URL.createObjectURL(await response.blob()), "_blank");
}

export async function uploadDocument(file: File): Promise<DocumentItem> {
  const id = createId();

  if (DEMO_MODE) {
    return {
      id,
      name: file.name,
      type: file.type || "application/octet-stream",
      size: file.size,
      uploadedAt: new Date().toISOString(),
      fileUrl: URL.createObjectURL(file),
      file
    };
  }

  const formData = new FormData();
  formData.append("file", file);

  const result = await request<{
    id: string;
    name: string;
    type?: string;
    size?: number;
    uploaded_at?: string;
  }>("/api/documents/upload", {
    method: "POST",
    body: formData
  });

  return {
    id: result.id,
    name: result.name,
    type: result.type || file.type,
    size: result.size ?? file.size,
    uploadedAt: result.uploaded_at || new Date().toISOString(),
    fileUrl: `/api/documents/${result.id}/file`
  };
}

export async function askQuestion(
  question: string,
  documents: DocumentItem[],
  history: ChatMessage[]
): Promise<ChatResponse> {
  if (DEMO_MODE) {
    const firstDocument = documents[0];

    // Demonstration only: this answer is not generated by an LLM
    // and does not represent a real retrieval result.
    return {
      answer: firstDocument
        ? `Das ist eine Beispielantwort im Demo-Modus. Deine Frage war: „${question}“.\n\nSobald das Backend angeschlossen ist, wird hier die tatsächliche Antwort deines RAG-Systems erscheinen. Aktuell wurde der Dokumentinhalt nicht analysiert.`
        : "Lade zuerst ein Dokument hoch. Im Demo-Modus wird noch keine echte Dokumentensuche ausgeführt.",
      sources: firstDocument
        ? [
            {
              documentId: firstDocument.id,
              documentName: firstDocument.name,
              page: 1,
              excerpt: "Beispielquelle – kein tatsächlich abgerufener Text."
            }
          ]
        : []
    };
  }

  return request<ChatResponse>("/api/chat", {
    method: "POST",
    headers: {
      "Content-Type": "application/json"
    },
    body: JSON.stringify({
      question,
      document_ids: documents.map((document) => document.id),
      history: history.map(({ role, content }) => ({ role, content }))
    })
  });
}

export type StreamHandlers = {
  onSources: (sources: Source[]) => void;
  onDelta: (text: string) => void;
  // cited is undefined when the backend does not report which sources were used
  onDone: (cited?: number[]) => void;
};

type StreamEvent =
  | { type: "sources"; sources: Source[] }
  | { type: "delta"; text: string }
  | { type: "done"; cited: number[] }
  | { type: "error"; detail: string };

export type StreamOptions = {
  // Sent to the backend: the model thinks longer before it answers.
  thinking?: boolean;
  // Aborting ends the stream and the backend stops generating.
  signal?: AbortSignal;
};

export function isAbort(error: unknown): boolean {
  return error instanceof DOMException && error.name === "AbortError";
}

export async function askQuestionStream(
  question: string,
  documents: DocumentItem[],
  history: ChatMessage[],
  handlers: StreamHandlers,
  options: StreamOptions = {}
): Promise<void> {
  if (DEMO_MODE) {
    const result = await askQuestion(question, documents, history);
    handlers.onSources(result.sources);
    handlers.onDelta(result.answer);
    handlers.onDone();
    return;
  }

  const response = await authFetch("/api/chat/stream", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    signal: options.signal,
    body: JSON.stringify({
      question,
      thinking: options.thinking ?? false,
      document_ids: documents.map((document) => document.id),
      history: history.map(({ role, content }) => ({ role, content }))
    })
  });
  if (!response.ok || !response.body) {
    throw new Error(await errorMessage(response));
  }

  const reader = response.body.getReader();
  const decoder = new TextDecoder();
  let buffer = "";
  let finished = false;

  const handle = (line: string) => {
    const event = JSON.parse(line) as StreamEvent;
    if (event.type === "sources") handlers.onSources(event.sources);
    else if (event.type === "delta") handlers.onDelta(event.text);
    else if (event.type === "done") {
      finished = true;
      handlers.onDone(event.cited);
    } else throw new Error(event.detail);
  };

  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    buffer += decoder.decode(value, { stream: true });
    const lines = buffer.split("\n");
    buffer = lines.pop() ?? "";
    lines.filter((line) => line.trim()).forEach(handle);
  }
  if (buffer.trim()) handle(buffer);
  if (!finished) throw new Error("Die Verbindung wurde unterbrochen.");
}

export function isDemoMode(): boolean {
  return DEMO_MODE;
}
